from app.rag_pipeline import answer_question


# ==========================================
# Main CLI Execution Module
# ==========================================
def main():
    # Prompt the user directly in the console for their research query string
    question = input("Ask your research question: ").strip()

    try:
        # Pass the input query string down to the core RAG orchestration manager pipeline
        result = answer_question(question)

        # --- Clean Terminal Layout Formatting ---
        print("\n" + "=" * 60)
        print("ANSWER")
        print("=" * 60)
        print(result["answer"])  # Output the text response generated by the language model

        # Print the deduplicated list array of source filenames utilized during reference lookup
        print("\nSOURCES")
        for source in result["sources"]:
            print(f"- {source}")

    # --- Tiered Exception Handling Framework ---
    # Catch anticipated domain exceptions (empty queries, model generation drops, or database client breaks)
    except (ValueError, RuntimeError, ConnectionError) as exc:
        print(f"\nError: {exc}")

    # Catch-all backup block preventing program crashes from any unhandled runtime anomalies
    except Exception as exc:
        print(f"\nUnexpected error: {exc}")


# Standard protective guard layout isolating interactive shell execution routines
if __name__ == "__main__":
    main()
